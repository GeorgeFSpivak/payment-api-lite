

CREATE TABLE transfers (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    sender_id BIGINT NOT NULL,
    receiver_id BIGINT NOT NULL,
    amount DECIMAL(19, 2) NOT NULL CHECK ( amount >= 2.00),
    created_at TIMESTAMP WITH TIME ZONE NOT NULL,

    CONSTRAINT fx_transfers_sender FOREIGN KEY (sender_id) REFERENCES users(id),
    CONSTRAINT fx_transfers_receiver FOREIGN KEY (receiver_id) REFERENCES users(id)
);
